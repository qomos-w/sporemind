export function lookupModelDefault(name: string, table: Record<string, number>): number | undefined {
  const keys = Object.keys(table).sort((a, b) => b.length - a.length)
  for (const key of keys) {
    if (name.startsWith(key)) {
      return table[key]
    }
  }
  return undefined
}

